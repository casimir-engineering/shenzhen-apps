#!/usr/bin/env python3
"""Build an opt-in headless benchmark; never sign, run, or call an AI provider."""
import argparse
import pathlib
import shlex
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'portable/mac/SPDFMacAITransport.mm'
HARNESS = pathlib.Path(__file__).with_name('benchmark.mm')


def replace_once(source: str, old: str, new: str) -> str:
    """Fail on upstream drift instead of silently losing a telemetry/budget hook."""
    count = source.count(old)
    if count != 1:
        raise RuntimeError(f'Transport hook expected once, found {count}: {old[:100]!r}')
    return source.replace(old, new, 1)


def instrument(source: str) -> str:
    hooks = [
        ('#import "SPDFMacAITransport.h"', '''#import "SPDFMacAITransport.h"
extern NSDictionary* SZBenchmarkProviderOptions(void);
extern NSError* SZBenchmarkBudgetError(void);
extern NSMutableArray* SZBenchmarkRequestBucket(void);
extern void SZBenchmarkResponse(NSData*,NSInteger,NSError*,NSTimeInterval,NSURLRequest*,NSMutableArray*);'''),
        ('    if (tools.count) { body[@"tools"]', '''    NSMutableDictionary* provider=[body[@"provider"] mutableCopy];
    provider[@"max_price"]=SZBenchmarkProviderOptions()[@"max_price"];
    body[@"provider"]=provider;
    if (tools.count) { body[@"tools"]'''),
        ('@property(nonatomic) NSMutableData* bytes;', '''@property(nonatomic) NSDate* benchmarkStarted;
@property(nonatomic) NSMutableArray* benchmarkBucket;
@property(nonatomic) NSMutableData* bytes;'''),
        ('    (void)task;\n    NSDictionary* message=nil;', '''    SZBenchmarkResponse(self.bytes,self.status,error,
        -self.benchmarkStarted.timeIntervalSinceNow,task.originalRequest,self.benchmarkBucket);
    NSDictionary* message=nil;'''),
        ('        NSError* error=nil;\n        NSURLRequest* request=', '''        NSError* budgetError=SZBenchmarkBudgetError();
        if(budgetError) {
            dispatch_async(dispatch_get_main_queue(),^{ if(completion)completion(nil,budgetError); });
            return;
        }
        NSError* error=nil;
        NSURLRequest* request='''),
        ('SPDFMacAIResponse* response=[SPDFMacAIResponse new]; response.bytes=',
         '''SPDFMacAIResponse* response=[SPDFMacAIResponse new];
        response.benchmarkStarted=NSDate.date;
        response.benchmarkBucket=SZBenchmarkRequestBucket();
        response.bytes='''),
    ]
    for old, new in hooks:
        source = replace_once(source, old, new)
    return '// Generated benchmark-only transport; production source is unchanged.\n' + source


def make_path(path: pathlib.Path) -> str:
    value = str(path)
    if any(c in value for c in '\n\r:#$\\'):
        raise ValueError('Build paths cannot contain newline, colon, #, $, or backslash.')
    return value.replace(' ', '\\ ')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=pathlib.Path, required=True,
                        help='Scratch directory outside the repository; created if necessary.')
    parser.add_argument('--generate-only', action='store_true',
                        help='Validate source hooks and generate transport/Makefile without compiling.')
    args = parser.parse_args()
    out = args.output_dir.expanduser().resolve()
    if out == ROOT or ROOT in out.parents:
        parser.error('Use a scratch output directory outside the repository.')
    instrumented = instrument(SOURCE.read_text())
    out.mkdir(parents=True, exist_ok=True)
    transport = out / 'benchmark-transport.mm'
    transport.write_text(instrumented)
    binary = out / 'ai-model-benchmark'
    makefile = out / 'benchmark.mk'
    objs = '$(filter-out %/SPDFMacAITransport.o,$(AI_READER_BASE_OBJS))'
    other = '$(CORE_OBJS) $(YAML_OBJ) $(MAC_MD4C_OBJ) $(MAC_GUMBO_OBJS)'
    headers = ' '.join(make_path(p) for p in HARNESS.parent.glob('*.h'))
    prerequisites = f'{make_path(HARNESS)} {headers} {make_path(transport)} {objs} {other}'
    sources = f'{shlex.quote(str(HARNESS))} {shlex.quote(str(transport))}'
    makefile.write_text(f'''# Generated by tools/ai-model-benchmark/build.py
{make_path(binary)}: {prerequisites}
\tclang++ $(MAC_TARGET_FLAGS) -std=c++17 -fobjc-arc -Imac -Icore -I$(MUPDF_DIR)/include {sources} {objs} {other} $(MUPDF_LIBS) -framework Cocoa -framework QuartzCore -framework PDFKit -framework ImageIO -framework UniformTypeIdentifiers -framework CoreServices -framework Security -framework LocalAuthentication -lm -Wl,-dead_strip -o {shlex.quote(str(binary))}
''')
    if not args.generate_only:
        subprocess.run(['make', '-C', str(ROOT / 'portable'), '-f', 'Makefile',
                        '-f', str(makefile), str(binary)], check=True)
    print(f'Generated: {transport}')
    print(f'Binary target: {binary}')
    print('Not signed or run. No provider requests made.')


if __name__ == '__main__':
    main()
