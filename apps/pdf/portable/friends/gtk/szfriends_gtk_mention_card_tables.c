gboolean szfriends_gtk_virama_block(gunichar c, gunichar *low, gunichar *high) {
    for (gsize i = 0; i + 2 < G_N_ELEMENTS(viramas); i += 3) {
        if (viramas[i] != c) continue;
        *low = viramas[i + 1];
        *high = viramas[i + 2];
        return TRUE;
    }
    return FALSE;
}

/* The scripts `c` is used with, into `scripts`: its Script_Extensions, or else its one Script, in `own`. */
static gsize scripts_of(gunichar c, const gunichar **scripts, gunichar *own) {
    gsize low = 0, high = G_N_ELEMENTS(script_extensions) / 4;
    while (low < high) {
        gsize middle = low + (high - low) / 2;
        const gunichar *entry = script_extensions + 4 * middle;
        if (c > entry[1]) low = middle + 1;
        else if (c < entry[0]) high = middle;
        else {
            *scripts = script_sets + entry[2];
            return entry[3];
        }
    }
    /* The last start at or before `c`; the first is U+0000. */
    for (low = 0, high = G_N_ELEMENTS(script_starts) / 2; high - low > 1;) {
        gsize middle = low + (high - low) / 2;
        if (script_starts[2 * middle] <= c) low = middle;
        else high = middle;
    }
    *own = script_starts[2 * low + 1];
    *scripts = own;
    return 1;
}

gboolean szfriends_gtk_mark_fits_letter(gunichar mark, gunichar letter) {
    gunichar mark_own = 0, letter_own = 0;
    const gunichar *mark_scripts = NULL, *letter_scripts = NULL;
    gsize marks = scripts_of(mark, &mark_scripts, &mark_own);
    gsize letters = scripts_of(letter, &letter_scripts, &letter_own);
    if (mark_scripts == &mark_own && mark_own == SCRIPT_INHERITED) return TRUE; /* no script of its own: U+0338 */
    for (gsize i = 0; i < marks; i++)
        for (gsize j = 0; j < letters; j++)
            if (mark_scripts[i] == letter_scripts[j]) return TRUE;
    return FALSE;
}

