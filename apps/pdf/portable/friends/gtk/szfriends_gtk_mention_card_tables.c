static gboolean in_ranges(gunichar c, const gunichar *ranges, gsize n_pairs) {
    gsize low = 0, high = n_pairs;
    while (low < high) {
        gsize middle = low + (high - low) / 2;
        if (c > ranges[2 * middle + 1]) low = middle + 1;
        else if (c < ranges[2 * middle]) high = middle;
        else return TRUE;
    }
    return FALSE;
}

#define IN(c, table) in_ranges(c, table, G_N_ELEMENTS(table) / 2)

