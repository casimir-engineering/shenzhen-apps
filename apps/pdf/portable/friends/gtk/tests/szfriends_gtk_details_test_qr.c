/* The mask a symbol carries in its first copy of the format bits, and whether that copy says level M. */
static int mask_of(const guint8 *modules, int size, gboolean *level_m) {
    int bits = 0;
    for (int i = 0; i <= 5; i++) bits |= modules[i * size + 8] << i;
    bits |= modules[7 * size + 8] << 6 | modules[8 * size + 8] << 7 | modules[8 * size + 7] << 8;
    for (int i = 9; i < 15; i++) bits |= modules[8 * size + 14 - i] << i;
    bits ^= 0x5412;
    *level_m = ((bits >> 13) & 3) == 0;
    return (bits >> 10) & 7;
}

static guint8 *from_rows(const char *const *rows, int size) {
    guint8 *modules = g_malloc0((gsize)size * size);
    for (int y = 0; y < size; y++)
        for (int x = 0; x < size; x++) modules[y * size + x] = rows[y][x] == '#';
    return modules;
}

static void expect_same(const char *payload, const char *const *rows, int size) {
    gboolean level_m = FALSE;
    guint8 *golden = from_rows(rows, size);
    int mask = mask_of(golden, size, &level_m), got = 0;
    guint8 *mine = szfriends_gtk_qr_encode(payload, mask, &got);
    EXPECT(level_m && mine && got == size && memcmp(mine, golden, (gsize)size * size) == 0,
           "\"%.20s…\": the same %dx%d symbol as libqrencode with mask %d", payload, size, size, mask);
    g_free(mine);
    g_free(golden);
}

void szfg_run_qr_tests(void) {
    char *eight = g_strnfill(150, 'x');
    expect_same("hi", version1, 21);
    expect_same("szfriends:add?id=cottage-violet&key=AbCdEfGhIjKlMnOpQrStUvWxYz0123456789-_abcde", version5, 37);
    expect_same(eight, version8, 49);
    /* Its own choice: a valid level-M mask whose symbol is exactly the forced one, so only the choice differs. */
    int size = 0, forced_size = 0;
    gboolean level_m = FALSE;
    guint8 *chosen = szfriends_gtk_qr_encode(eight, -1, &size);
    int mask = chosen ? mask_of(chosen, size, &level_m) : -1;
    guint8 *forced = szfriends_gtk_qr_encode(eight, mask, &forced_size);
    EXPECT(chosen && level_m && forced && memcmp(chosen, forced, (gsize)size * size) == 0,
           "the chosen mask is written into the format bits");
    g_free(chosen);
    g_free(forced);
    g_free(eight);
    const struct { int length, size; } capacity[] = {{14, 21}, {15, 25}, {84, 37}, {85, 41}, {213, 57}};
    for (gsize i = 0; i < G_N_ELEMENTS(capacity); i++) {
        char *payload = g_strnfill(capacity[i].length, 'a');
        guint8 *modules = szfriends_gtk_qr_encode(payload, -1, &size);
        EXPECT(modules && size == capacity[i].size, "%d bytes fit a %dx%d symbol (%d)", capacity[i].length,
               capacity[i].size, capacity[i].size, size);
        g_free(modules);
        g_free(payload);
    }
    char *too_long = g_strnfill(214, 'a');
    EXPECT(szfriends_gtk_qr_encode(too_long, -1, &size) == NULL, "past version 10 there is no QR, not a wrong one");
    EXPECT(szfriends_gtk_qr_encode(NULL, -1, &size) == NULL, "nor for nothing");
    g_free(too_long);
}
